def generate_sales_data(anchors: List[Anchor], products: List[Product]) -> List[Dict]:
    sales_data = []
    
    for anchor in anchors:
        dialect = mapper.get_dialect_by_province(anchor.hometown)
        
        matching_products = [p for p in products if dialect in str(p.origin) or anchor.hometown in str(p.origin)]
        
        if matching_products:
            product = random.choice(matching_products)
        else:
            product = random.choice(products)
        
        platform_multiplier = {
            "抖音": 1.5,
            "快手": 1.2,
            "视频号": 0.8,
            "淘宝直播": 1.0,
            "拼多多直播": 0.9,
            "B站": 0.6
        }
        
        followers_multiplier = anchor.followers / 1000000
        base_sales = random.randint(5000, 50000)
        sales_volume = int(base_sales * platform_multiplier.get(anchor.platform, 1.0) * followers_multiplier)
        
        sales_data.append({
            "anchor_id": anchor.id,
            "product_id": product.id,
            "sales_volume": max(1000, sales_volume)
        })
    
    return sales_data


